-- Cérvix-AI · esquema de base de datos (PostgreSQL)
-- Equivale a src/common/db_models.py. Es OPCIONAL: la API crea estas tablas sola al arrancar.
-- Útil para documentar el diseño o para crear la base a mano. Se puede ejecutar varias veces.

CREATE TABLE IF NOT EXISTS usuario (  -- añadida al diseño original: el front tiene registro/login
    id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80)  NOT NULL,
    apellidos       VARCHAR(80)  NOT NULL,
    email           VARCHAR(160) NOT NULL UNIQUE,
    profesion       VARCHAR(60)  NOT NULL,
    institucion     VARCHAR(120) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    rol             VARCHAR(20)  NOT NULL DEFAULT 'profesional',
    objetivo        VARCHAR(80),
    fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('profesional', 'asesor_medico', 'administrador'))
);

CREATE TABLE IF NOT EXISTS sesion (
    id_sesion   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario  INTEGER NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    expira_en   TIMESTAMPTZ NOT NULL,
    creada_en   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sesion_usuario ON sesion (id_usuario);

CREATE TABLE IF NOT EXISTS categoria_analisis (
    id_categoria  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(30) NOT NULL UNIQUE,
    nombre        VARCHAR(80) NOT NULL,
    descripcion   TEXT
);

CREATE TABLE IF NOT EXISTS version_modelo (
    id_version           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_modelo        VARCHAR(80)  NOT NULL,
    fecha_entrenamiento  DATE         NOT NULL,
    parametros           TEXT,
    ruta_archivo         VARCHAR(255) NOT NULL,
    estado               VARCHAR(10)  NOT NULL DEFAULT 'activo',
    CONSTRAINT ck_version_estado CHECK (estado IN ('activo', 'archivado'))
);
-- Solo un modelo vigente a la vez (opcional, refuerza la regla en la base de datos)
CREATE UNIQUE INDEX IF NOT EXISTS ux_un_modelo_activo ON version_modelo (estado) WHERE estado = 'activo';

CREATE TABLE IF NOT EXISTS resultado_prueba (
    id_resultado         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario           INTEGER          NOT NULL REFERENCES usuario (id_usuario),
    id_version           INTEGER          NOT NULL REFERENCES version_modelo (id_version),
    id_categoria         INTEGER          NOT NULL REFERENCES categoria_analisis (id_categoria),
    fecha_prueba         TIMESTAMPTZ      NOT NULL DEFAULT now(),
    confianza            DOUBLE PRECISION NOT NULL,
    tiempo_respuesta_ms  INTEGER          NOT NULL,
    CONSTRAINT ck_resultado_confianza CHECK (confianza BETWEEN 0 AND 1),
    CONSTRAINT ck_resultado_tiempo    CHECK (tiempo_respuesta_ms >= 0)
);
CREATE INDEX IF NOT EXISTS idx_resultado_version   ON resultado_prueba (id_version);
CREATE INDEX IF NOT EXISTS idx_resultado_categoria ON resultado_prueba (id_categoria);

CREATE TABLE IF NOT EXISTS muestra_analisis (
    id_muestra     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_resultado   INTEGER NOT NULL UNIQUE REFERENCES resultado_prueba (id_resultado) ON DELETE CASCADE,
    nombre_archivo VARCHAR(255) NOT NULL,
    modalidad      VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS metrica_evaluacion (
    id_metrica     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_version     INTEGER          NOT NULL REFERENCES version_modelo (id_version),
    exactitud      DOUBLE PRECISION NOT NULL,
    sensibilidad   DOUBLE PRECISION NOT NULL,
    especificidad  DOUBLE PRECISION NOT NULL,  -- añadida: la guía exige especificidad (RNF-01.1)
    f1             DOUBLE PRECISION NOT NULL,
    fecha_calculo  TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT ck_metrica_rango CHECK (
        exactitud BETWEEN 0 AND 1 AND sensibilidad BETWEEN 0 AND 1
        AND especificidad BETWEEN 0 AND 1 AND f1 BETWEEN 0 AND 1
    )
);
CREATE INDEX IF NOT EXISTS idx_metrica_version ON metrica_evaluacion (id_version);